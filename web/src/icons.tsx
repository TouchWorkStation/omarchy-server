export type IconName = keyof typeof icons

export function hasIcon(name: string): name is IconName {
	return Object.hasOwn(icons, name)
}

export function Icon({name, size = 22, stroke = 1.75, className, style}: {name: IconName; size?: number; stroke?: number; className?: string; style?: React.CSSProperties}) {
	const Component = icons[name]
	return <Component size={size} stroke={stroke} className={className} style={style} aria-hidden="true" />
}
